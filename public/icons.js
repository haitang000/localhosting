/**
 * @param {string} name  key from PATHS
 * @param {{cls?: string, size?: number|string, title?: string}} [opts]
 *   `cls` adds classes (`lg` for 1.15em, `muted` to fade it); `title` makes
 *   the icon a labelled image instead of decoration — only pass it when the
 *   icon stands alone, otherwise the label beside it is read twice.
 */
export function icon(name, { cls = '', size, title } = {}) {
  const d = PATHS[name];
  if (!d) return '';
  const style = size ? ` style="width:${size};height:${size}"` : '';
  const a11y = title ? ` role="img" aria-label="${title}"` : ' aria-hidden="true"';
  return `<svg class="ico ${cls}" viewBox="0 0 24 24" fill="none" stroke="currentColor"
    stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round"${style}${a11y}>${d}</svg>`;
}

export const hasIcon = (name) => Object.hasOwn(PATHS, name);
